"""สร้างบทสำหรับอัดเสียง (context/recording.md) จาก script.md — ตัดป้าย claim และคำอธิบายภาพออก

    uv run python tools/make_recording.py

ไฟล์นี้สร้างใหม่ทุกครั้ง: แก้บทที่ script.md เท่านั้น
"""

from pathlib import Path

from check_claims import SCRIPT, narration

OUT = SCRIPT.parent / "recording.md"

GUIDE = """# บทอัดเสียง — ทะเลสองฝั่ง ฟังภูมิอากาศคนละแบบ

> สร้างจาก `script.md` ด้วย `tools/make_recording.py` — อย่าแก้ไฟล์นี้โดยตรง

## วิธีอัด (ราว 1–2 ชั่วโมงรวมรีเทค)

1. **ห้องเงียบที่มีของนุ่ม** (ผ้าม่าน เตียง ตู้เสื้อผ้าเปิด) — ปิดพัดลม/แอร์ช่วงอัด · มือถือเปิดโหมดเครื่องบิน
2. **มือถืออัดดีกว่าไมค์โน้ตบุ๊ก** — ถือห่างปาก 15–20 ซม. เยื้องไปข้างเล็กน้อย (กันลมจากตัว พ ป)
   เลือกไฟล์ WAV ถ้าแอปให้เลือก ไม่ได้ก็ m4a คุณภาพสูงสุด
3. **หนึ่งไฟล์ต่อหนึ่งตอน** ตั้งชื่อ `SQ01.wav` … `SQ10.wav` (นามสกุลตามที่แอปให้)
4. **เริ่มแต่ละไฟล์ด้วยความเงียบ 3 วินาที** — ผมใช้ช่วงนี้วัด noise ของห้องเพื่อลบออก
5. **พูดผิด: หยุด 2 วินาที แล้วอ่านทั้งประโยคใหม่** — ไม่ต้องหยุดอัด ผมตัดเทคที่ผิดออกเอง
6. อ่านช้ากว่าคุยปกติเล็กน้อย เว้นจังหวะระหว่างประโยค ~1 วินาที · **อ่านตัวเลขตามที่เขียนทุกตัว**
   (ผมตรวจเสียงจริงกับบทด้วยเครื่องอีกรอบ ถ้าเลขผิดจะขออัดประโยคนั้นใหม่)
7. ประโยคที่มี ✂ อ่านไว้ด้วย — ตัดออกได้ภายหลังถ้าคลิปยาวเกิน
8. เสร็จแล้ววางไฟล์ทั้งหมดใน `presentation/audio/narration/raw/` แล้วบอกผม

## คำอ่านศัพท์ (แนะนำ — ใช้แบบที่คุณถนัดได้ แต่ให้เหมือนกันทั้งคลิป)

| เขียน | อ่าน |
|---|---|
| Niño3.4 | นีโญ สามจุดสี่ |
| SOI · DMI · IOD | เอส-โอ-ไอ · ดี-เอ็ม-ไอ · ไอ-โอ-ดี |
| WNPMI | ดับเบิลยู-เอ็น-พี-เอ็ม-ไอ |
| PSMSL | พี-เอส-เอ็ม-เอส-แอล |
| PASC | พี-เอ-เอส-ซี |
| K1 · P1 | เค-วัน · พี-วัน |
| FIR · Kaiser · taps | เอฟ-ไอ-อาร์ · ไคเซอร์ · แท็ปส์ |
| CWT · Morlet · octave | ซี-ดับเบิลยู-ที · มอร์เลต์ · อ็อกเทฟ |
| coherence · aliasing · Welch | โคฮีเรนซ์ · เอเลียสซิง · เวลช์ |
| AR(1) | เอ-อาร์-วัน |
| 1997 ถึง 98 | หนึ่งเก้าเก้าเจ็ด ถึง เก้าแปด (หรือแบบที่ถนัด) |
"""


def main():
    lines = narration(SCRIPT.read_text())
    parts, current_sq, n = [GUIDE], None, 0
    for shot, _, sentence, _ in lines:
        sq = shot.split("_")[0]
        if sq != current_sq:
            current_sq, n = sq, 0
            parts.append(f"\n## {sq} → ไฟล์ `{sq}.wav`\n")
        n += 1
        parts.append(f"{n}. {sentence}")
    OUT.write_text("\n".join(parts) + "\n")
    print(f"recording.md: {len(lines)} ประโยค")


if __name__ == "__main__":
    main()
